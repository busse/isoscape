// Drives the built explorer's series page in headless Chrome (sandbox on, file://, no server)
// and checks what a visitor does with it. Screenshots go to shots/<round>/.
import { createRequire } from 'node:module'
const require = createRequire(import.meta.url)
const { chromium } = require('/opt/npm-tools/node_modules/playwright-core')

const round = process.argv[2] || 'i1'
const OUT = '/home/claude/scratch-tt/shots/' + round + '/'
const BASE = 'file:///home/claude/scratch-tt/site/index.html'
const fs = await import('node:fs')
fs.mkdirSync(OUT, { recursive: true })
const results = []
const check = (name, ok, extra = '') => { results.push((ok ? 'PASS ' : 'FAIL ') + name + (extra ? ' :: ' + extra : '')); }

const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', chromiumSandbox: true, headless: true })
const errors = []
const ready = async (page) => { await page.waitForFunction(() => { const i = document.querySelector('.tt .tt-a'); return i && i.complete && i.naturalWidth > 0 }, null, { timeout: 15000 }) }
const state = (page) => page.evaluate(() => ({ hash: location.hash, cap: [...document.querySelectorAll('.tt-cap .tt-y')].map((e) => e.textContent).join('|'), a: document.querySelector('.tt-a').dataset.year, b: document.querySelector('.tt-b').dataset.year || null, scrollY: document.scrollingElement.scrollTop, bodyScroll: document.body.scrollTop }))

// ---- desktop --------------------------------------------------------------------------------
{
  const ctx = await browser.newContext({ viewport: { width: 1280, height: 711 } })
  await ctx.addInitScript(() => { window.__copied = []; try { Object.defineProperty(navigator, 'clipboard', { value: { writeText: (t) => { window.__copied.push(t); return Promise.resolve() } } }) } catch (e) {} })
  const page = await ctx.newPage()
  page.on('pageerror', (e) => errors.push('desktop: ' + e.message))
  page.on('console', (m) => { if (m.type() === 'error' && !/ERR_FILE_NOT_FOUND|Failed to load resource/.test(m.text())) errors.push('desktop console: ' + m.text()) })
  await page.goto(BASE + '#/downtown-through-time')
  await ready(page)
  let s = await state(page)
  check('opens on the featured year 1925', s.cap === '1925' && s.a === '1925', JSON.stringify(s))
  await page.click('.tt-step[data-d="1"]')
  await page.waitForTimeout(400)
  s = await state(page)
  check('next button shows 1930 and writes the route', s.cap === '1930' && s.hash === '#/downtown-through-time/1930' && s.a === '1930', JSON.stringify(s))
  await page.keyboard.press('ArrowLeft'); await page.keyboard.press('ArrowLeft')
  await page.waitForTimeout(400)
  s = await state(page)
  check('arrow keys step back two years (1920)', s.cap === '1920', JSON.stringify(s))
  // scrub along the timeline from its left end to about 1865
  const line = await page.locator('.tt-line').boundingBox()
  await page.mouse.move(line.x + 2, line.y + 22)
  await page.mouse.down()
  s = await state(page)
  check('pressing the timeline\'s left end shows 1737', s.cap === '1737', JSON.stringify(s))
  const dot1865 = await page.locator('.tt-dot[data-y="1865"]').boundingBox()
  await page.mouse.move(dot1865.x + 4, line.y + 22, { steps: 8 })
  await page.mouse.up()
  await page.waitForTimeout(500)
  s = await state(page)
  check('scrubbing to the 1865 dot shows 1865', s.cap === '1865' && s.a === '1865', JSON.stringify(s))
  await page.screenshot({ path: OUT + 'd1-scrubbed-1865.png' })
  // compare
  await page.click('.tt-nav .tt-mode')
  await page.waitForFunction(() => document.querySelector('.tt-b').dataset.year)
  s = await state(page)
  check('Compare two years pairs the year shown (left) with today (right)', s.hash === '#/downtown-through-time/1865..2026' && s.cap === 'Left1865|Right2026', JSON.stringify(s))
  await page.selectOption('[data-side="b"]', '1870')
  await page.waitForTimeout(500)
  s = await state(page)
  check('Later year picker: 1870', s.hash === '#/downtown-through-time/1865..1870' && s.b === '1870', JSON.stringify(s))
  await page.selectOption('[data-side="b"]', '1860')
  await page.waitForTimeout(300)
  s = await state(page)
  check('a later year before the earlier one moves the earlier back (1850..1860), earlier stays left', s.hash === '#/downtown-through-time/1850..1860', JSON.stringify(s))
  await page.selectOption('[data-side="a"]', '1865'); await page.selectOption('[data-side="b"]', '1870')
  await page.waitForTimeout(500)
  const badge = await page.evaluate(() => [document.querySelector('.tt-div').getAttribute('data-badge'), document.querySelector('.tt-ta').textContent, document.querySelector('.tt-tb').textContent])
  check('divider and both sides labelled with years', badge[0] === '1865 │ 1870' && badge[1] === '1865' && badge[2] === '1870', JSON.stringify(badge))
  // drag the divider
  const st = await page.locator('.tt-stage').boundingBox()
  await page.mouse.move(st.x + st.width / 2, st.y + st.height / 2)
  await page.mouse.down()
  await page.mouse.move(st.x + st.width * 0.3, st.y + st.height / 2, { steps: 6 })
  await page.mouse.up()
  const clip = await page.evaluate(() => [document.querySelector('.tt-clip').style.clipPath, document.querySelector('.tt-div').style.left, document.querySelector('.tt-div').getAttribute('aria-valuenow')])
  check('mouse drag moves the divider to 30%', clip[2] === '30', JSON.stringify(clip))
  await page.focus('.tt-div'); await page.keyboard.press('Shift+ArrowRight')
  const kv = await page.evaluate(() => document.querySelector('.tt-div').getAttribute('aria-valuenow'))
  check('Shift+→ on the focused divider moves it 10%', kv === '40', kv)
  await page.screenshot({ path: OUT + 'd2-compare-1865-1870-divider.png' })
  // zoom and pan
  await page.click('[data-z="in"]'); await page.click('[data-z="in"]')
  await page.waitForTimeout(200)
  const before = await page.evaluate(() => document.querySelector('.tt-a').style.left)
  await page.mouse.move(st.x + st.width * 0.7, st.y + st.height * 0.6)
  await page.mouse.down(); await page.mouse.move(st.x + st.width * 0.5, st.y + st.height * 0.5, { steps: 5 }); await page.mouse.up()
  const after = await page.evaluate(() => [document.querySelector('.tt-a').style.left, document.querySelector('.tt-div').getAttribute('aria-valuenow'), document.querySelector('.tt-stage').style.touchAction])
  check('zoomed in, a drag away from the divider pans and leaves the divider', before !== after[0] && after[1] === '40' && after[2] === 'none', JSON.stringify([before, after]))
  await page.screenshot({ path: OUT + 'd3-compare-zoomed.png' })
  await page.click('[data-z="fit"]')
  // copy link
  await page.click('.tt-link')
  await page.waitForTimeout(200)
  const copied = await page.evaluate(() => [window.__copied, document.querySelector('.tt-link').textContent])
  check('Copy link copies the share page with the two years', /s\/page-downtown-through-time\.html#\/downtown-through-time\/1865\.\.1870$/.test(copied[0][0] || '') && copied[1] === 'Copied', JSON.stringify(copied))
  // full viewer link
  const full = await page.evaluate(() => document.querySelector('.tt-full').getAttribute('href'))
  check('full viewer link uses lasting routes', full === '#richmond-downtown-time:1865..richmond-downtown-time:1870', full)
  // jump link from the list
  await page.evaluate(() => { document.getElementById('page').scrollTop = 10000 })
  await page.click('a[href="#/downtown-through-time/1950..1960"]')
  await page.waitForTimeout(600)
  s = await state(page)
  const vis = await page.evaluate(() => { const r = document.querySelector('.tt').getBoundingClientRect(); return r.top })
  check('jump link sets 1950..1960 and brings the view into sight', s.hash === '#/downtown-through-time/1950..1960' && vis >= 0 && vis < 300, JSON.stringify([s, vis]))
  check('no page-level scroll (window and body stay at 0)', s.scrollY === 0 && s.bodyScroll === 0, JSON.stringify(s))
  // back goes to the previous route
  await page.goBack(); await page.waitForTimeout(400)
  s = await state(page)
  check('Back returns to the state before the jump link', s.hash === '#/downtown-through-time/1865..1870', JSON.stringify(s))
  // show one year
  await page.click('.tt-pick .tt-mode')
  await page.waitForTimeout(300)
  s = await state(page)
  check('Show one year keeps the earlier year', s.hash === '#/downtown-through-time/1865' && s.cap === '1865', JSON.stringify(s))
  // the old viewer route still works, and links to the page
  await page.goto(BASE + '#richmond-downtown-time:1925')
  await page.waitForTimeout(800)
  const vw = await page.evaluate(() => ({ reading: document.body.classList.contains('reading'), go: (document.querySelector('#timeline a.ttgo') || {}).getAttribute?.('href'), info: [...document.querySelectorAll('#links a')].map((a) => a.textContent)[0] }))
  check('old route #richmond-downtown-time:1925 still opens the viewer, with a link to the page', !vw.reading && vw.go === '#/downtown-through-time/1925' && /series page/.test(vw.info), JSON.stringify(vw))
  await page.screenshot({ path: OUT + 'd4-viewer-with-link.png' })
  await page.click('#timeline a.ttgo')
  await page.waitForTimeout(800)
  s = await state(page)
  check('the viewer\'s link opens the page at its year', s.hash === '#/downtown-through-time/1925' && s.cap === '1925', JSON.stringify(s))
  // compare route from the viewer
  await page.goto(BASE + '#richmond-downtown-time:1865..richmond-downtown-time:1870')
  await page.waitForTimeout(800)
  const vc = await page.evaluate(() => ({ cmp: document.querySelector('#divider').style.display, first: [...document.querySelectorAll('#links a')][0].getAttribute('href') }))
  check('viewer compare route still works and its page link carries both years', vc.cmp === 'block' && vc.first === '#/downtown-through-time/1865..1870', JSON.stringify(vc))
  // front page hero
  await page.goto(BASE + '#home')
  await page.waitForTimeout(800)
  const hero = await page.evaluate(() => [...document.querySelectorAll('.hero')].map((h) => [h.querySelector('a.pic').getAttribute('href'), h.querySelector('.acts a').textContent, (h.querySelector('.years a') || {}).getAttribute?.('href')]))
  check('front page hero goes to the page', hero.some((h) => h[0] === '#/downtown-through-time/1925' && h[1] === 'Step through the years' && h[2] === '#/downtown-through-time/1737'), JSON.stringify(hero))
  await page.screenshot({ path: OUT + 'd5-home.png' })
  // a share page's fragment (as the share page passes it on) opens the state
  await page.goto(BASE + '#/downtown-through-time/1737..2026')
  await ready(page)
  s = await state(page)
  check('a fragment #/downtown-through-time/1737..2026 opens that pair', s.cap === 'Left1737|Right2026', JSON.stringify(s))
  await page.goto(BASE + '#/downtown-through-time/2026..1737')
  await ready(page)
  s = await state(page)
  check('a reversed pair is put earlier-left', s.cap === 'Left1737|Right2026', JSON.stringify(s))
  await page.goto(BASE + '#/downtown-through-time/how-it-was-made')
  await page.waitForTimeout(700)
  const sec = await page.evaluate(() => { const h = document.getElementById('p-downtown-through-time-how-it-was-made'); return h ? Math.round(h.getBoundingClientRect().top) : null })
  check('a section route still scrolls to its heading', sec !== null && sec < 120, String(sec))
  await ctx.close()
}

// ---- phone (emulated touch) -------------------------------------------------------------------
{
  const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true, deviceScaleFactor: 2 })
  const page = await ctx.newPage()
  page.on('pageerror', (e) => errors.push('phone: ' + e.message))
  await page.goto(BASE + '#/downtown-through-time')
  await ready(page)
  await page.tap('.tt-step[data-d="-1"]')
  await page.waitForTimeout(400)
  let s = await state(page)
  check('phone: tapping ← shows 1920', s.cap === '1920', JSON.stringify(s))
  await page.tap('.tt-nav .tt-mode')
  await page.waitForFunction(() => document.querySelector('.tt-b').dataset.year)
  s = await state(page)
  check('phone: compare 1920..2026', s.hash === '#/downtown-through-time/1920..2026', JSON.stringify(s))
  // a sideways touch drag on the picture moves the divider (CDP touch events: emulated, not a real finger)
  const cdp = await ctx.newCDPSession(page)
  const st = await page.locator('.tt-stage').boundingBox()
  const y = st.y + st.height / 2
  const touch = async (type, x, yy) => cdp.send('Input.dispatchTouchEvent', { type, touchPoints: type === 'touchEnd' ? [] : [{ x, y: yy, id: 1 }] })
  await touch('touchStart', st.x + st.width * 0.5, y)
  for (let i = 1; i <= 10; i++) await touch('touchMove', st.x + st.width * (0.5 - i * 0.03), y)
  await touch('touchEnd')
  await page.waitForTimeout(200)
  const v = await page.evaluate(() => document.querySelector('.tt-div').getAttribute('aria-valuenow'))
  check('phone: a sideways touch drag moves the divider (emulated touch)', Number(v) <= 25, v)
  await page.screenshot({ path: OUT + 'p1-compare-after-touch-drag.png' })
  // a vertical touch swipe on the picture scrolls the page's box
  const top0 = await page.evaluate(() => document.getElementById('page').scrollTop)
  await touch('touchStart', st.x + st.width * 0.6, y)
  for (let i = 1; i <= 10; i++) await touch('touchMove', st.x + st.width * 0.6, y - i * 15)
  await touch('touchEnd')
  await page.waitForTimeout(500)
  const after = await page.evaluate(() => [document.getElementById('page').scrollTop, document.querySelector('.tt-div').getAttribute('aria-valuenow')])
  check('phone: a vertical swipe on the picture scrolls the page and leaves the divider (emulated touch)', after[0] > top0 && after[1] === v, JSON.stringify([top0, after]))
  // timeline scrub by touch
  await page.tap('.tt-pick .tt-mode')
  await page.evaluate(() => { document.getElementById('page').scrollTop = 0 })
  await page.waitForTimeout(300)
  const ln = await page.locator('.tt-line').boundingBox()
  await touch('touchStart', ln.x + ln.width * 0.5, ln.y + 22)
  for (let i = 1; i <= 8; i++) await touch('touchMove', ln.x + ln.width * (0.5 - i * 0.05), ln.y + 22)
  await touch('touchEnd')
  await page.waitForTimeout(500)
  s = await state(page)
  check('phone: a sideways touch drag along the timeline scrubs to an earlier year (emulated touch)', Number(s.cap) < 1900, JSON.stringify(s))
  const wide = await page.evaluate(() => [document.documentElement.scrollWidth, document.getElementById('page').scrollWidth, document.getElementById('page').clientWidth])
  check('phone: nothing wider than the screen', wide[0] <= 390 && wide[1] <= wide[2], JSON.stringify(wide))
  await page.screenshot({ path: OUT + 'p2-after-scrub.png' })
  await ctx.close()
}

await browser.close()
console.log(results.join('\n'))
console.log(errors.length ? 'ERRORS:\n' + errors.join('\n') : 'no page errors')
